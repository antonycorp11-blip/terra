test('mostra províncias, fronteiras e névoa, com zoom contínuo e arraste', async ({ page }) => {
  await page.setViewportSize({ width:1440, height:860 })
  await foundHouse(page)
  expect(await page.locator('path[data-province]').count()).toBe(252)
  expect(await page.locator('path[data-knowledge="0"]').count()).toBeGreaterThan(230)
  await expect(page.locator('[data-player-seat]')).toHaveCount(1)
  expect(await page.locator('[data-layer="realm-borders"] > g').count()).toBe(7)
  expect(await page.locator('[data-layer="fief-borders"] > g').count()).toBe(42)
  expect(await page.locator('[data-explorable]').count()).toBeGreaterThan(3)
  await expect(page.locator('[data-province-label]')).toHaveText(['Pontevela'])
  // Every settlement type has an icon.
  await page.getByRole('button', { name:'Aproximar' }).click()
  await page.getByRole('button', { name:'Aproximar' }).click()
  const icons = await page.locator('[data-map-building] use').evaluateAll(nodes => nodes.map(node => node.getAttribute('href')))
  expect(icons.length).toBe(4)
  for (const href of icons) expect(await page.locator(`symbol${href}`).count()).toBe(1)
  await expect(page.locator('text[data-province-label]')).toHaveCount(1)
  // Wheel zoom and drag move only the camera.
  const scale = Number(await map(page).getAttribute('data-scale'))
  await page.mouse.move(500, 450); await page.mouse.wheel(0, 600)
  await expect.poll(async () => Number(await map(page).getAttribute('data-scale'))).toBeLessThan(scale)
  const layer = map(page).locator(':scope > g').first()
  const before = await layer.getAttribute('transform')
  await page.mouse.move(500, 450); await page.mouse.down(); await page.mouse.move(580, 480, { steps:8 }); await page.mouse.up()
  await expect(layer).not.toHaveAttribute('transform', before!)
  await expect(panel(page).getByRole('heading', { name:'Fronteiras de Varedor' })).toBeVisible()
  // The calendar advancing never resets the camera.
  const moved = await layer.getAttribute('transform')
  await page.getByTitle('Muito rápido').click(); await page.waitForTimeout(700); await page.getByTitle('Pausar').click()
  await expect(layer).toHaveAttribute('transform', moved!)
})

test('ciclo completo do MVP persiste após salvar e carregar', async ({ page }) => {
  test.setTimeout(180_000)
  await page.setViewportSize({ width:1440, height:860 })
  await foundHouse(page, 'Draven')
  // Invest in the province economy.
  await page.getByRole('button', { name:'Influenciar' }).click()
  await panel(page).locator('[data-investment="market"]').getByRole('button', { name:/Investir/ }).click()
  await expect(panel(page).getByText(/Em obras · 25 dias restantes/)).toBeVisible()
  await expect(page.locator('[data-resource="gold"] strong')).toHaveText('480')
  // Send an expedition to a sighted frontier.
  await page.getByRole('button', { name:'Descobrir' }).click()
  const target = (await page.locator('[data-explorable]').first().getAttribute('data-explorable'))!
  await province(page, target).dispatchEvent('click')
  await expect(panel(page).getByRole('heading', { name:'Terras avistadas' })).toBeVisible()
  await panel(page).getByRole('button', { name:/Enviar expedição/ }).click()
  await expect(page.locator(`[data-expedition-marker="${target}"]`)).toBeVisible()
  await waitFor(page, /Expedição concluída/)
  await expect(page.locator(`path[data-province="${target}"]`)).toHaveAttribute('data-knowledge', '2')
  await province(page, target).dispatchEvent('click')
  await expect(panel(page).getByText('Relatório da expedição')).toBeVisible()
  // Diplomacy: send an emissary and meet the ruler.
  await panel(page).getByRole('button', { name:/Enviar emissário/ }).click()
  await waitFor(page, /Primeiro contato/)
  await province(page, target).dispatchEvent('click')
  await expect(panel(page).getByText('Por que esta relação?')).toBeVisible()
  await panel(page).getByRole('button', { name:/Enviar presente/ }).click()
  await panel(page).getByRole('button', { name:/Conversar com/ }).click()
  await panel(page).getByRole('button', { name:'Cumprimentar' }).click()
  await expect(panel(page).locator('[aria-live="polite"]')).toContainText('Amizade')
  await expect(panel(page).getByRole('button', { name:/Cumprimentar/ })).toBeDisabled()
  // Espionage: hire and send an agent.
  await panel(page).getByRole('button', { name:'‹ Voltar' }).click()
  await panel(page).getByRole('button', { name:/^‹/ }).first().click()
  await panel(page).getByRole('tab', { name:'Espiões' }).click()
  await panel(page).locator('[data-agent="agent-0"]').getByRole('button', { name:/Contratar/ }).click()
  await province(page, target).dispatchEvent('click')
  await panel(page).getByRole('button', { name:/Enviar Nara/ }).click()
  await waitFor(page, /Relatório —/)
  await province(page, target).dispatchEvent('click')
  await expect(panel(page).locator(`[data-report="${target}"]`).first()).toContainText('Fonte: Nara')
  // Save, start over, load: everything is back.
  const day = await page.locator('header').getByTitle(/Dia/).innerText()
  await page.getByRole('button', { name:'Abrir menu' }).click()
  await page.getByRole('button', { name:'Salvar', exact:true }).click()
  await page.getByRole('button', { name:'Salvar campanha' }).click()
  await expect(page.getByText(/Campanha salva/)).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name:'Carregar campanha' }).click()
  await page.getByRole('button', { name:/^Campanha da Casa Draven/ }).click()
  await expect(page.getByRole('button', { name:'Abrir menu' })).toContainText('Casa Draven')
  await expect(page.locator('header').getByTitle(/Dia/)).toHaveText(day)
  await expect(page.locator(`path[data-province="${target}"]`)).toHaveAttribute('data-knowledge', /[23]/)
  await page.getByRole('button', { name:'Influenciar' }).click()
  await panel(page).getByRole('tab', { name:'Espiões' }).click()
  await expect(panel(page).getByText('Fonte: Nara', { exact:false }).first()).toBeVisible()
  await panel(page).getByRole('tab', { name:'Relações' }).click()
  await expect(panel(page).getByText(/Neutra|Amigável|Desconfiada|Hostil/).first()).toBeVisible()
})

