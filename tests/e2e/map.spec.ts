test('arrastar o mapa move a câmera sem abrir território', async ({ page }) => {
  await page.goto('/', { waitUntil:'domcontentloaded' })
  const map=page.getByRole('img', { name:'Mapa político interativo de Varedor' })
  const terrain=map.locator(':scope > g').first()
  const before=await terrain.getAttribute('transform')
  await page.mouse.move(800,450)
  await page.mouse.down()
  await page.mouse.move(875,475,{steps:8})
  await page.mouse.up()
  await expect(terrain).not.toHaveAttribute('transform',before!)
  await expect(page.getByRole('complementary')).toHaveCount(0)
})

test('a arte carrega, capitais ficam livres dos rótulos e barcos navegam', async ({page})=>{
  await page.setViewportSize({width:1600,height:900})
  await page.goto('/',{waitUntil:'networkidle'})
  expect(await page.evaluate(async()=>{const image=new Image();image.src='/assets/varedor-map-atlas.png';await image.decode();return image.naturalWidth})).toBeGreaterThan(1000)
  await expect(page.locator('use[href="#art-tree"],use[href="#art-pine"],use[href="#art-mountain"]')).toHaveCount(0)
  const collisions=await page.evaluate(()=>{
    const buildings=[...document.querySelectorAll('[data-map-building]')]
    const labels=[...document.querySelectorAll('[data-map-label]')]
    return buildings.flatMap(building=>{
      const sprite=building.querySelector('use')!,matrix=sprite.getScreenCTM()!
      const topLeft=new DOMPoint(sprite.x.baseVal.value,sprite.y.baseVal.value).matrixTransform(matrix)
      const bottomRight=new DOMPoint(sprite.x.baseVal.value+sprite.width.baseVal.value,sprite.y.baseVal.value+sprite.height.baseVal.value).matrixTransform(matrix)
      const caption=building.querySelector('text')?.getBoundingClientRect()
      const a={left:Math.min(topLeft.x,caption?.left??Infinity),right:Math.max(bottomRight.x,caption?.right??-Infinity),top:topLeft.y,bottom:Math.max(bottomRight.y,caption?.bottom??-Infinity)}
      return labels.filter(label=>{const b=label.getBoundingClientRect();return a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top}).map(label=>[building.getAttribute('data-map-building'),label.getAttribute('data-map-label')])
    })
  })
  expect(collisions).toEqual([])
  const ship=page.locator('[data-ship]').first()
  const position=()=>ship.evaluate(el=>{const m=(el as SVGGraphicsElement).getCTM()!;return {x:m.e,y:m.f}})
  const start=await position()
  await expect.poll(async()=>{const next=await position();return Math.hypot(next.x-start.x,next.y-start.y)},{timeout:6000}).toBeGreaterThan(2)
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(page.locator('[data-sailing]')).toHaveAttribute('data-sailing','paused')
  const paused=await position()
  await page.waitForTimeout(300)
  expect(await position()).toEqual(paused)
})
