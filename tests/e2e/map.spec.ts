import { expect, test } from '@playwright/test'

test('abre apenas o mapa e permite entrar no território pelo clique', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/', { waitUntil:'domcontentloaded' })
  await expect(page.getByRole('img', { name:'Mapa político interativo de Varedor' })).toBeVisible()
  await expect(page.getByRole('complementary')).toHaveCount(0)
  await page.locator('path[data-territory="realm-1"]').first().click()
  await expect(page.getByRole('complementary', { name:'Detalhes do território' }).getByRole('heading', { name:'Velária' })).toBeVisible()
  await page.getByRole('button', { name:/Três Pontes/ }).click()
  await expect(page.getByRole('complementary').getByRole('heading', { name:'Três Pontes' })).toBeVisible()
  await page.getByRole('button', { name:/Pontevela/ }).click()
  await expect(page.getByRole('complementary').getByRole('heading', { name:'Pontevela' })).toBeVisible()
  await page.getByRole('complementary', { name:'Detalhes do território' }).getByRole('button', { name:/Castelo da Ponte Alta/ }).click()
  await expect(page.getByText('Guarnição')).toBeVisible()
  await expect(page.getByText('75', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:/Entrar em Pontevela/ }).click()
  await expect(page.getByRole('heading', { name:'Castelo da Ponte Alta' })).toBeVisible()
  const audienceArt=page.getByRole('img', { name:/Intendente no salão de Pontevela/ })
  await expect(audienceArt).toBeVisible()
  expect(await audienceArt.evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await expect(page.getByText('Crônica local')).toBeVisible()
  await page.getByRole('button', { name:/Distribuir mantimentos/ }).click()
  await expect(page.getByText('82%', { exact:true })).toBeVisible()
  await expect(page.getByText(/distribuiu cento e vinte sacas/).first()).toBeVisible()
  await page.getByRole('button', { name:'Voltar ao mapa' }).click()
  await page.getByRole('button', { name:'Fechar detalhes' }).click()
  await expect(page.getByRole('complementary')).toHaveCount(0)
})

test('o menu oculto controla o calendário e os salvamentos', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/', { waitUntil:'domcontentloaded' })
  await page.getByRole('button', { name:'Abrir menu' }).click()
  const date=page.getByText(/Dia \d+ · 128 AP/)
  await expect(date).toContainText('Dia 1 · 128 AP')
  await page.getByTitle('Muito rápido').click()
  await expect(date).not.toContainText('Dia 1 · 128 AP')
  await page.getByTitle('Pausar').click()
  const savedDate=await date.innerText()
  await page.getByRole('button', { name:'Salvar', exact:true }).click()
  await page.getByRole('button', { name:'Salvar campanha' }).click()
  await expect(page.getByText(/Campanha salva/)).toBeVisible()
  await page.getByRole('button', { name:'Abrir menu' }).click()
  await page.getByRole('button', { name:'Nova campanha' }).click()
  await page.getByRole('button', { name:'Iniciar como Casa Serraval' }).click()
  await page.getByRole('button', { name:'Abrir menu' }).click()
  await expect(date).toContainText('Dia 1 · 128 AP')
  await page.getByRole('button', { name:'Carregar' }).click()
  await page.getByRole('button', { name:/^Campanha de Serraval/ }).click()
  await page.getByRole('button', { name:'Abrir menu' }).click()
  await expect(date).toHaveText(savedDate)
})

