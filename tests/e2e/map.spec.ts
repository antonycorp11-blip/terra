import { expect, test, type Page } from '@playwright/test'

const map = (page: Page) => page.getByRole('img', { name:'Mapa político interativo de Varedor' })
const panel = (page: Page) => page.getByRole('complementary', { name:'Painel contextual' })
const province = (page: Page, id: string) => page.locator(`path[data-province="${id}"]`)

async function foundHouse(page: Page, name = 'Ravencor') {
  await page.goto('/', { waitUntil:'domcontentloaded' })
  await page.getByRole('button', { name:'Nova Campanha' }).click()
  await page.getByLabel('Nome da casa').fill(name)
  await page.getByRole('button', { name:'Continuar ›' }).click()
  await page.getByRole('button', { name:'Continuar ›' }).click()
  await page.getByRole('button', { name:'Fundar Minha Casa' }).click()
  await expect(map(page)).toBeVisible()
}
async function waitFor(page: Page, text: RegExp) {
  await page.getByTitle('Muito rápido').click()
  await expect(page.getByRole('button', { name:text }).first()).toBeVisible({ timeout:40_000 })
}

