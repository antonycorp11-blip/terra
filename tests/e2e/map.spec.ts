test('a arte do atlas carrega e os barcos navegam respeitando movimento reduzido', async ({ page }) => {
  await page.setViewportSize({ width:1600, height:900 })
  await foundHouse(page)
  expect(await page.evaluate(async () => { const image = new Image(); image.src = '/assets/varedor-map-atlas.png'; await image.decode(); return image.naturalWidth })).toBeGreaterThan(1000)
  await expect(page.locator('use[href="#art-tree"],use[href="#art-pine"],use[href="#art-mountain"]')).toHaveCount(0)
  const ship = page.locator('[data-ship]').first()
  const position = () => ship.evaluate(el => { const m = (el as SVGGraphicsElement).getCTM()!; return { x:m.e, y:m.f } })
  const start = await position()
  await expect.poll(async () => { const next = await position(); return Math.hypot(next.x - start.x, next.y - start.y) }, { timeout:6000 }).toBeGreaterThan(2)
  await page.emulateMedia({ reducedMotion:'reduce' })
  await expect(page.locator('[data-sailing]')).toHaveAttribute('data-sailing', 'paused')
  const paused = await position()
  await page.waitForTimeout(300)
  expect(await position()).toEqual(paused)
})
